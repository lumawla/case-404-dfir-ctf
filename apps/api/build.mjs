// Bundles the API (and the shared workspace package) into dist/server.js.
import { build } from "esbuild";

await build({
  entryPoints: ["src/server.ts"],
  outfile: "dist/server.js",
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  sourcemap: true,
  external: ["fastify", "@fastify/*"],
  banner: { js: "// CASE 404 API — generated by build.mjs" },
});
console.log("API built to dist/server.js");
